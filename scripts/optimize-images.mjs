import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
const root=new URL('../public/',import.meta.url),out=new URL('assets/optimized/',root);
await fs.mkdir(out,{recursive:true});
const sources=['assets/mascot.png',...(await fs.readdir(new URL('assets/products/',root))).filter(n=>/\.(jpg|png|webp)$/i.test(n)).map(n=>'assets/products/'+n)];
const manifest={};let before=0,after=0;
for(const src of sources){
 const bytes=await fs.readFile(new URL(src,root)),meta=await sharp(bytes).metadata();
 const hash=crypto.createHash('sha256').update(bytes).update('webp-v1-q82').digest('hex').slice(0,16);
 const variants={};
 for(const width of [160,320,640,960]){
  const w=Math.min(width,meta.width),name=hash+'-'+width+'.webp';
  const output=await sharp(bytes).rotate().resize({width:w,withoutEnlargement:true}).webp({quality:82,effort:5}).toBuffer();
  await fs.writeFile(new URL(name,out),output);variants[width]={url:'/assets/optimized/'+name,width:w};
  if(width===960){before+=bytes.length;after+=output.length;}
 }
 manifest['/'+src]={variants,width:meta.width,height:meta.height};
}
await fs.writeFile(new URL('image-manifest.mjs',root),'// Generated by scripts/optimize-images.mjs.\nexport const imageManifest='+JSON.stringify(manifest)+';\n');
console.log(JSON.stringify({originalBytes:before,largestWebpBytes:after,savedPercent:Math.round((1-after/before)*100)}));
